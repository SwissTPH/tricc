    def _fhirpath_as_decimal(self, expr: str, original_ref=None) -> str:
        """Force a FHIRPath operand to decimal so HAPI can compare it to a number.

        HAPI ``opGreaterOrEqual`` rejects string vs integer. Numeric calculates
        used to be Questionnaire ``string`` items (age_in_months), and even an
        integer item compared to ``2`` is safer as decimal vs decimal.
        See fix/20260821-fhirpath-numeric-compare.md.
        """
        s = (expr or "").strip()
        if not s:
            return expr
        if s.endswith(".toDecimal()") or s.endswith(".toInteger()"):
            return expr
        if original_ref is not None and (
            self._is_boolean_item_reference(original_ref)
            or self._is_choice_reference(original_ref)
            or self._operation_returns_boolean(original_ref)
        ):
            return expr
        if _NUMERIC_LITERAL.fullmatch(s):
            return format_fhirpath_decimal(s)
        return f"({s}).toDecimal()"

    def _fhirpath_numeric_operand(self, expr: str, original_ref=None) -> str:
        wrapped = self._wrap_operand_if_needed(expr, original_ref)
        return self._fhirpath_as_decimal(wrapped, original_ref)

