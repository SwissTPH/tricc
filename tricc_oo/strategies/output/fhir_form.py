    def tricc_operation_get_inherited_value(self, ref_expressions, original_references=None):
        """Multi-version value merge, CQL flavour (see fix/20260820-opensrp-inherited-value.md).

        Helper access is keyed by *concept*, so every version of the same node
        serialises to the same accessor string: deduplicate instead of emitting
        ``Coalesce(x, x)``. What is left after dedup is the value the dedup
        ``initialExpression`` already pulls from the current encounter.
        """
        unique = []
        for expr in ref_expressions:
            if expr not in unique:
                unique.append(expr)
        if not unique:
            raise NotImplementedError("GET_INHERITED_VALUE without operand")
        if len(unique) == 1:
            return unique[0]
        return self.tricc_operation_coalesce(unique)

