    def _answer_value_suffix(self, original_ref) -> str:
        """FHIRPath suffix that reads the scalar answer value for ``original_ref``."""
        if self._is_choice_reference(original_ref):
            return ".value.code"
        return ".value"

    def _choice_answer_collection(self, answer_expr: str) -> str:
        """Strip any ``.value[.Coding].code`` suffix so we have the ``…answer`` collection."""
        base = answer_expr or ""
        for suffix in (".valueCoding.code", ".value.code"):
            if base.endswith(suffix):
                return base[: -len(suffix)]
        return base

    def _choice_membership_expr(self, answer_expr: str, code_expr: str) -> str:
        """True when a choice answer includes ``code_expr``.

        HAPI FHIRPath on ``QuestionnaireResponse.item.answer`` exposes polymorphic
        ``value``, not ``valueCoding``. ``'code' in …answer.valueCoding.code`` is
        always empty/false. ``answer.where(value.code = 'x').exists()`` matches
        a selected option.
        """
        answers = self._choice_answer_collection(answer_expr)
        return f"{answers}.where(value.code = {code_expr}).exists()"

    def _choice_codes_expr(self, answer_expr: str) -> str:
        """Collection of choice codes from an ``…answer`` FHIRPath."""
        answers = self._choice_answer_collection(answer_expr)
        if answers.endswith(".answer"):
            return f"{answers}.value.code"
        return f"{answer_expr}.value.code" if answer_expr else answer_expr

    def _operation_returns_boolean(self, expr) -> bool:
        """True when ``expr`` is a boolean TriccOperation (walks parenthesis)."""
        if isinstance(expr, TriccOperation):
            if expr.operator == TriccOperator.PARENTHESIS and expr.reference:
                return self._operation_returns_boolean(expr.reference[0])
            return expr.operator in RETURNS_BOOLEAN or expr.operator in (
                TriccOperator.ISNULL,
                TriccOperator.CAST_BOOLEAN,
            )
        return False

