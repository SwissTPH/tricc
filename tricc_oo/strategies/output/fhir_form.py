    def _find_item_anywhere(self, link_id: str):
        """Search every Questionnaire for ``link_id`` (nested groups included)."""
        if not link_id:
            return None
        for q in (self.questionnaires or {}).values():
            item = self._find_item_by_link_id(q.get("item", []), link_id)
            if item is not None:
                return item
        return None

    def _is_boolean_item_reference(self, original_ref) -> bool:
        """True when ``original_ref`` is a native boolean Questionnaire item."""
        if original_ref is None:
            return False
        if isinstance(original_ref, TriccNodeSelectYesNo):
            return True
        if isinstance(original_ref, TriccNodeSelect) and self._is_yesno_boolean_select(original_ref):
            return True
        link_id = None
        if isinstance(original_ref, TriccReference):
            try:
                link_id = get_export_name(original_ref.value)
            except Exception:
                link_id = str(original_ref.value)
        elif issubclass(getattr(original_ref, "__class__", object), TriccNodeBaseModel):
            try:
                link_id = get_export_name(original_ref)
            except Exception:
                link_id = getattr(original_ref, "name", None)
        item = self._find_item_anywhere(link_id) if link_id else None
        return bool(item and item.get("type") == "boolean")

    def _is_choice_reference(self, original_ref) -> bool:
        """True when ``original_ref`` is a choice / open-choice item (not yes/no boolean)."""
        if original_ref is None or self._is_boolean_item_reference(original_ref):
            return False
        if isinstance(original_ref, TriccNodeSelect):
            return True
        link_id = None
        if isinstance(original_ref, TriccReference):
            try:
                link_id = get_export_name(original_ref.value)
            except Exception:
                link_id = str(original_ref.value)
        elif issubclass(getattr(original_ref, "__class__", object), TriccNodeBaseModel):
            try:
                link_id = get_export_name(original_ref)
            except Exception:
                link_id = getattr(original_ref, "name", None)
        item = self._find_item_anywhere(link_id) if link_id else None
        if item is not None:
            return item.get("type") in ("choice", "open-choice")
        # Unknown references stay on .value for scalar wrap; SELECTED/CONTAINS
        # still treat unresolved operands as coded membership (see those emitters).
        return False

    def _is_string_item_reference(self, original_ref) -> bool:
        """True when CONTAINS should stay a substring test rather than code membership."""
        if original_ref is None:
            return False
        tricc_type = getattr(original_ref, "tricc_type", None)
        if tricc_type == TriccNodeType.text:
            return True
        link_id = None
