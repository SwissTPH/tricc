@register_output_strategy("FHIRStrategy")
class FHIRStrategy(BaseOutPutStrategy):
    """Standard FHIR SDC output strategy.

    Generates Questionnaire, Library+CQL, StructureMap/FLM, ValueSet, Binary,
    and FSH files from a TRICC project graph.

    Attributes:
        processes: List of process names to handle (default ``["main"]``).
        base_url: Canonical base URL for generated resources.
        questionnaires: Dict mapping process name → Questionnaire resource dict.
        cql_defines: Dict mapping process name → list of CQL define strings.
        structuremaps: Dict mapping process name → StructureMap resource dict.
        valuesets: Dict mapping list_name → ValueSet resource dict.
        binaries: List of Binary resource dicts (images).
    """

    processes = ["main"]
    project = None
    output_path = None

    def __init__(self, project, output_path: str, base_url: str = DEFAULT_BASE_URL, use_value_sets: bool = False):
        """Initialise the FHIRStrategy.

        Args:
            project: The TRICC project object.
            output_path: Directory path for output files.
            base_url: Canonical base URL for FHIR resources.
            use_value_sets: If True, generate external ValueSets and reference them via answerValueSet.
                            If False (default), hardcode options directly in the Questionnaire as answerOption
                            (easier for standalone testing).
        """
        super().__init__(project, output_path)
        self.base_url = (base_url or "https://fhir.tricc").rstrip("/")
        self.use_value_sets = use_value_sets
        self.questionnaires: Dict[str, dict] = {}
        self.cql_defines: Dict[str, List[str]] = {}
        self.structuremaps: Dict[str, dict] = {}
        self.extraction_maps: Dict[str, dict] = {}
        self.extraction_rules: Dict[str, list] = {}
        self.valuesets: Dict[str, dict] = {}
        self.binaries: List[dict] = []
        self._image_binary_ids: Dict[str, str] = {}
        self._project_image_index: Optional[Dict[str, str]] = None
        self._form_id: Optional[str] = None
        self.cql_libraries: Dict[str, str] = {}
        self.libraries: Dict[str, dict] = {}   # Phase 2: actual FHIR Library resources
        self.fml_mappings: Dict[str, str] = {}
        # Simple stack for building nested Questionnaire items (groups/activities)
        self._group_stack: list[tuple[str, dict]] = []

    def get_tricc_operation_expression(self, operation):
        # For CQL
        ref_expressions = []
        original_references = []
        if not hasattr(operation, "reference"):
            return self.get_tricc_operation_operand(operation)
        for r in operation.reference:
            if isinstance(r, list):
                r_expr = [
                    (
                        self.get_tricc_operation_expression(sr)
                        if isinstance(sr, TriccOperation)
                        else self.get_tricc_operation_operand(sr)
                    )
                    for sr in r
                ]
                original_references.append(r)
            elif isinstance(r, TriccOperation):
                r_expr = self.get_tricc_operation_expression(r)
                original_references.append(r)
            else:
                r_expr = self.get_tricc_operation_operand(r)
                original_references.append(r)
            if isinstance(r_expr, TriccReference):
                r_expr = self.get_tricc_operation_operand(r_expr)
            ref_expressions.append(r_expr)

        # build lower level
        if hasattr(self, f"tricc_operation_{operation.operator}"):
            callable = getattr(self, f"tricc_operation_{operation.operator}")
            return callable(ref_expressions, original_references)
        else:
            raise NotImplementedError(
                f"This type of operation '{operation.operator}' is not supported in this strategy"
            )

    def resolve_form_id(self, start_pages=None) -> str:
        """Resolve and cache the project form id (folder name; may contain ``_``).

        Args:
            start_pages: Optional start_pages dict; defaults to ``project.start_pages``.

        Returns:
            Raw form id string used for output paths.
        """
        if getattr(self, "_form_id", None):
            return self._form_id
        pages = start_pages if start_pages is not None else getattr(self.project, "start_pages", None)
        form_id = "fhir-form"
        if pages and "main" in pages:
            root = getattr(pages["main"], "root", None)
            form_id = (getattr(root, "form_id", None) if root else None) or form_id
        elif getattr(self.project, "form_id", None):
            form_id = self.project.form_id
        self._form_id = form_id
        return form_id

    @property
    def fhir_form_id(self) -> str:
        """FHIR-safe form id prefix for resource ids (no underscores)."""
        return to_fhir_id(getattr(self, "_form_id", None) or "fhir-form")

    def execute(self):
        """Run the full FHIR export pipeline."""
        version = datetime.datetime.now().strftime("%Y%m%d%H%M")
        logger.info(f"FHIRStrategy: build version {version}")
        # Resolve form id before library assembly so Library ids match PlanDefinitions
        self.resolve_form_id()
        if "main" in self.project.start_pages:
            self._group_stack = []  # reset nesting stack for a fresh run
            self.process_base(self.project.start_pages, pages=self.project.pages, version=version)
        else:
            logger.critical("Main process required")
            return

        logger.info("FHIRStrategy: generating relevance (enableWhenExpression)")
        self.process_relevance(self.project.start_pages, pages=self.project.pages)
        logger.info("FHIRStrategy: generating calculate (initialExpression / CQL)")
        self.process_calculate(self.project.start_pages, pages=self.project.pages)
        logger.info("FHIRStrategy: generating export (StructureMap)")
        self.process_export(self.project.start_pages, pages=self.project.pages)
        self._assemble_extraction_maps()

        # Build the actual CQL library texts from collected defines (Phase 2)
        # Must happen before export()
        self._assemble_cql_libraries()

        logger.info("FHIRStrategy: writing output files")
        self._sanitize_questionnaires()
        self.export(self.project.start_pages, version=version)
        logger.info("FHIRStrategy: validating")
        self.validate()

        # Final visibility log (helps developers immediately see the state of the FHIR export)
        logger.info(
            f"FHIRStrategy complete: {len(self.questionnaires)} questionnaire(s), "
            f"{len(self.cql_libraries)} CQL library file(s) written, "
            f"{len(self.fml_mappings)} FML mapping(s). "
            "See validate() output above for completeness warnings."
        )

    _YESNO_TRUE_MARKERS = {"true", "yes", "1", "y"}
    _YESNO_FALSE_MARKERS = {"false", "no", "0", "n"}

    def _boolean_choice_orientation_extension(self) -> Optional[dict]:
        """Rendering hint for visible boolean Questionnaire items.

        Generic FHIR SDC has none. ``OpenSRPStrategy`` overrides this to emit
        ``questionnaire-choiceOrientation=horizontal`` so Yes/No sit side by
        side. See ``feature/20260819-boolean-choice-orientation.md``.
        """
        return None

    @classmethod
    def _is_yesno_boolean_select(cls, node):
        """True if a select_one node's 2 options are a yes/no (true/false) pair,
        the case rendered as a native FHIR boolean item instead of a choice."""
        options = getattr(node, "options", None) or {}
        if len(options) != 2:
            return False
        markers = cls._YESNO_TRUE_MARKERS | cls._YESNO_FALSE_MARKERS
        opt_names = {str(o.name).lower() for o in options.values()}
        opt_codes = {str(getattr(o, "code", "")).lower() for o in options.values()}
        return bool(opt_names & markers or opt_codes & markers)

    @classmethod
    def _yesno_option_boolean_literal(cls, option):
        """FHIRPath boolean literal ('true'/'false', unquoted) for a select option
        belonging to a yes/no boolean-mapped select, or None if it isn't one."""
        marker = str(getattr(option, "code", None) or option.name).lower()
        if marker in cls._YESNO_TRUE_MARKERS:
            return "true"
        if marker in cls._YESNO_FALSE_MARKERS:
            return "false"
        return None

    def _get_project_image_content(self, file_name: str) -> Optional[str]:
        """Look up the base64 payload for a draw.io-embedded image by file name.

        ``project.images`` is populated once, at parse time, by
        ``xml_to_tricc.enrich_node``/``process_edges`` for every node/option
        that had an image-decorator box wired to it — it is the only place
        the actual image bytes live once parsing is done (the on-disk
        ``media-tmp/images/`` copy is not reachable from an output strategy,
        which only knows ``output_path``). Indexed lazily and cached since
        every question/option in a form is resolved against it.

        Args:
            file_name: Image file name as stored on ``node.image``/``opt.image``.

        Returns:
            The base64-encoded image payload, or ``None`` if not found.
        """
        if self._project_image_index is None:
            self._project_image_index = {
                entry["file_path"]: entry["image_content"]
                for entry in (getattr(self.project, "images", None) or [])
                if entry.get("file_path")
            }
        return self._project_image_index.get(file_name)

    def _register_image_binary(self, file_name: Optional[str]) -> Optional[Tuple[str, str]]:
        """Ensure a Binary resource exists for an image file, returning (id, contentType).

        Idempotent: the same file name always resolves to the same Binary id
        (deterministic UUID5, like every other resource id in this strategy),
        and is only appended to ``self.binaries`` once even if referenced from
        several questions/options.

        Args:
            file_name: Image file name as stored on ``node.image``/``opt.image``,
                or ``None``/empty if the node/option has no image.

        Returns:
            ``(binary_id, content_type)``, or ``None`` if there is no image,
            its type is unsupported, or its content could not be found.
        """
        if not file_name:
            return None
        content_type = image_content_type(file_name)
        if content_type is None:
            logger.warning("Image '%s' has no recognizable content type, skipping", file_name)
            return None
        if file_name in self._image_binary_ids:
            return self._image_binary_ids[file_name], content_type
        content = self._get_project_image_content(file_name)
        if content is None:
            logger.warning("Image '%s' referenced by a node but no content found, skipping", file_name)
            return None
        form_key = self.resolve_form_id()
        binary_id = fhir_resource_id(form_key, "Binary", file_name)
        self.binaries.append({
            "resourceType": "Binary",
            "id": binary_id,
            "contentType": content_type,
            "data": content,
        })
        self._image_binary_ids[file_name] = binary_id
        return binary_id, content_type

    def _build_item_media_extension(self, file_name: Optional[str]) -> Optional[dict]:
        """Build an itemMedia extension for a question's ``.image``, if any."""
        registered = self._register_image_binary(file_name)
        if registered is None:
            return None
        binary_id, content_type = registered
        return build_item_media_extension(binary_id, content_type)

    def _build_item_answer_media_extension(self, file_name: Optional[str]) -> Optional[dict]:
        """Build an itemAnswerMedia extension for an answer option's ``.image``, if any."""
        registered = self._register_image_binary(file_name)
        if registered is None:
            return None
        binary_id, content_type = registered
        return build_item_answer_media_extension(binary_id, content_type)

    def generate_base(self, node, **kwargs):
        """Build a Questionnaire.item from a TRICC node using the central mapper.

        Supports basic nesting: group-like nodes (activity_start, start, etc.)
        become "group" items and subsequent siblings are attached under them
        until a corresponding end node is seen.
        """
        tricc_type = getattr(node, 'tricc_type', None)
        if tricc_type is None:
            tricc_type = getattr(node, 'type', None) or str(getattr(node, '__class__', '')).lower()

        if should_skip(tricc_type) or isinstance(node, TriccNodeSelectOption):
            return True

        # Segment / process
        segment = self._node_segment(node)

        if segment not in self.questionnaires:
            form_key = self.resolve_form_id()
            q_id = fhir_resource_id(form_key, "Questionnaire", segment)
            q_name = to_fhir_id("questionnaire", segment)
            # "main" is the project's single root process (1 project = 1 Intervention):
            # its human title is the root node's authored label (same source other
            # output strategies use, e.g. xls_form.py/html_form.py), not the segment slug.
            q_title = q_name
            if segment == "main":
                main_page = self.project.start_pages.get("main")
                root_label = getattr(getattr(main_page, "root", None), "label", None)
                if root_label:
                    q_title = root_label
            self.questionnaires[segment] = {
                "resourceType": "Questionnaire",
                "id": q_id,
                "url": f"{self.base_url}/Questionnaire/{q_id}",
                "name": q_name,
                "title": q_title,
                "status": "draft",
                # openSRP QuestionnaireActivity requires subjectType (Patient for client forms)
                "subjectType": ["Patient"],
                "item": []
            }


        fhir_type = get_fhir_item_type(tricc_type)

        if fhir_type is None:
            # Purely structural/navigation node (activity_end, end, goto, link_in,
            # link_out, exclusive) — never rendered as a Questionnaire item. Still
            # pop the group stack for end/activity_end so nesting stays balanced.
            if tricc_type in ("end", "activity_end") and self._group_stack:
                self._group_stack.pop()
            return True

        # Special case requested: treat "yesno" style select_one as native boolean
        if fhir_type == "choice" and self._is_yesno_boolean_select(node):
            fhir_type = "boolean"

        if fhir_type == "string" and self._expression_returns_boolean(node):
            fhir_type = "boolean"

        label = getattr(node, 'label', None) or getattr(node, 'text', None) or ''
        # FIXME, does not work like this
        if isinstance(label, TriccOperation):
            # Display injection (CONCATENATE) or multi-lang: render via op expression / first locale
            label = self.get_tricc_operation_expression(label)
        hidden = fhir_type != "group" and (
            is_hidden(tricc_type) or isinstance(node, TriccNodeDisplayCalculateBase)
        )
        if hidden:
            label = self._sanitize_hidden_item_text(node, label)
        item = {
            "linkId": get_export_name(node),
            "text": label,
            "type": fhir_type,
        }

        if is_repeating(tricc_type):
            item["repeats"] = True

        extensions = get_display_type_extensions(
            getattr(node, 'display_type', None), tricc_type
        )
        # Groups must never carry questionnaire-hidden: SDC-aware renderers hide
        # a group's entire subtree along with it, masking all nested questions.
        if hidden:
            extensions.append(build_hidden_extension())
        media_extension = self._build_item_media_extension(getattr(node, "image", None))
        if media_extension:
            extensions.append(media_extension)
        if fhir_type == "boolean" and not hidden:
            orientation_ext = self._boolean_choice_orientation_extension()
            if orientation_ext:
                extensions.append(orientation_ext)
        if extensions:
            item["extension"] = extensions

        if should_emit_repeat_metadata(node):
            item.setdefault("extension", []).append(
                build_questionnaire_repeat_extension(get_repeat(node))
            )

        # Handle options (same logic as before)
        # Skip for boolean (e.g. select_yesno) — they use native true/false instead of choice options
        if fhir_type != "boolean" and hasattr(node, 'options') and node.options:
            if self.use_value_sets:
                pass  # Phase 3
            item["answerOption"] = []
            for opt in node.options.values():
                option_entry = {"valueCoding": self._answer_option_coding(opt)}
                answer_media_extension = self._build_item_answer_media_extension(
                    getattr(opt, "image", None)
                )
                if answer_media_extension:
                    option_entry["extension"] = [answer_media_extension]
                item["answerOption"].append(option_entry)

        # === Nesting logic (basic) ===
        is_group_starter = fhir_type == "group" and tricc_type in (
            "start", "activity_start", "page"
        )

        q = self.questionnaires[segment]
        target_list = q["item"]

        if self._group_stack:
            # We are inside a group — append to the top of the stack's "item" list
            _, parent_item = self._group_stack[-1]
            target_list = parent_item.setdefault("item", [])

        target_list.append(item)

        if is_group_starter:
            # Push this item onto the stack so children attach under it
            self._group_stack.append((segment, item))

        return True

    def generate_relevance(self, node, **kwargs):
        """Attach enableWhenExpression / option toggles (or hide the item)."""
        self._attach_option_toggles(node)

        relevance = self._effective_relevance(node)
        if relevance is None:
            return True

        segment = getattr(node, 'segment', None) or 'main'
        if segment not in self.questionnaires:
            return True

        fhirpath_expr = self.convert_expression_to_fhirpath(relevance)

        item = self._find_item_by_link_id(self.questionnaires[segment].get("item", []), get_export_name(node))
        if item is not None:
            if fhirpath_expr == 'false':
                item.setdefault("extension", []).append(build_hidden_extension())
            elif fhirpath_expr != 'true':
                item.setdefault("extension", []).append(
                    build_enable_when_expression(fhirpath_expr)
                )
        return True

    @staticmethod
    def _is_effective_relevance(rel) -> bool:
        if rel is None or rel is True or rel == "":
            return False
        if isinstance(rel, TriccStatic) and rel.value in (True, "true", ""):
            return False
        return isinstance(rel, (TriccOperation, TriccReference, TriccStatic, str)) or rel is False

    def _effective_relevance(self, node):
        """Relevance to emit on this Questionnaire item.

        Page / activity groups are authored as ``activity.relevance`` (XLSForm
        begin-group relevant). The activity_start node's own ``relevance`` is
        often ``true`` even when the page is gated (demo Page-2 = hungry OR bad_p).
        """
        tricc_type = getattr(node, "tricc_type", None)
        act = getattr(node, "activity", None)
        act_rel = getattr(act, "relevance", None) if act is not None else None
        if (
            isinstance(tricc_type, str)
            and tricc_type in ("start", "activity_start", "page")
            and self._is_effective_relevance(act_rel)
        ):
            return act_rel
        node_rel = getattr(node, "relevance", None)
        if self._is_effective_relevance(node_rel):
            return node_rel
        return None

    def _answer_option_coding(self, opt) -> dict:
        """Return the valueCoding dict used on both answerOption and toggle slices."""
        concept = lookup_codesystems_code(self.project.code_systems, opt.name)
        if concept:
            coding = {"code": concept.code, "display": concept.display}
            system = getattr(concept, "system", None)
            if system:
                coding["system"] = system
            return coding
        return {"code": opt.name, "display": getattr(opt, "label", opt.name)}

    def _option_relevance_is_always_on(self, relevance) -> bool:
        if relevance is None or relevance is True:
            return True
        if isinstance(relevance, TriccStatic) and relevance.value in (True, "true"):
            return True
        return False

    def _attach_option_toggles(self, node) -> None:
        """Emit answerOptionsToggleExpression for options that have relevance.

        Select options are not Questionnaire items, so their relevance is attached
        to the parent choice item (SDC context is Questionnaire.item).
        """
        options = getattr(node, "options", None)
        if not options or self._is_yesno_boolean_select(node):
            return

        segment = getattr(node, "segment", None) or "main"
        q = self.questionnaires.get(segment)
        if not q:
            return
        item = self._find_item_by_link_id(q.get("item", []), get_export_name(node))
        if item is None:
            return

        grouped = {}
        order = []
        for opt in options.values():
            relevance = getattr(opt, "relevance", None)
            if self._option_relevance_is_always_on(relevance):
                continue
            try:
                fhirpath_expr = self.convert_expression_to_fhirpath(relevance)
            except NotImplementedError as exc:
                logger.debug(
                    "Skipping option toggle for %s on %s: %s",
                    getattr(opt, "name", None),
                    get_export_name(node),
                    exc,
                )
                continue
            if fhirpath_expr == "true":
                continue
            if fhirpath_expr not in grouped:
                grouped[fhirpath_expr] = []
                order.append(fhirpath_expr)
            grouped[fhirpath_expr].append(self._answer_option_coding(opt))

        for fhirpath_expr in order:
            item.setdefault("extension", []).append(
                build_answer_options_toggle_expression(grouped[fhirpath_expr], fhirpath_expr)
            )

    @staticmethod
    def _find_item_by_link_id(items, link_id):
        """Recursively search a Questionnaire item list (including group children)
        for an item with the given linkId."""
        for item in items:
            if item.get("linkId") == link_id:
                return item
            child = FHIRStrategy._find_item_by_link_id(item.get("item", []), link_id)
            if child is not None:
                return child
        return None

    @staticmethod
    def _collect_calculate_references(expression):
        """Flatten a calculate node's expression_reference/reference into the leaf
        node/TriccReference objects it depends on (skips plain literals)."""
        if isinstance(expression, TriccOperation):
            return list(expression.get_references())
        if isinstance(expression, list):
            refs = []
            for e in expression:
                refs.extend(FHIRStrategy._collect_calculate_references(e))
            return refs
        if isinstance(expression, TriccReference):
            return [expression]
        if expression is not None and issubclass(expression.__class__, TriccNodeBaseModel):
            return [expression]
        return []

    def generate_calculate(self, node, **kwargs):
        """Record the calculate node's value source and attach the matching SDC
        extension: calculatedExpression (FHIRPath) when it can be recomputed live
        from other items already in this Questionnaire, otherwise initialExpression
        (CQL, evaluated once at $populate) when it depends on data outside the form
        (e.g. observation history reachable only through the CQL Helper library)."""
        tricc_type = getattr(node, "tricc_type", None)
        if tricc_type not in CALCULATE_NODE_TYPES and not isinstance(node, TriccNodePopulate):
            # Not a value-producing calculate node (e.g. a group/navigation node
            # such as activity_start/activity_end/link_out) — nothing to attach.
            return True

        segment = getattr(node, "segment", "main")
        q = self.questionnaires.get(segment)
        if not q:
            return True

        link_id = get_export_name(node)
        calc_name = f"Calc_{link_id}"

        if isinstance(node, TriccNodePopulate):
            cql_expr = resolve_populate_reference(node, qualified=True)
            if segment not in self.cql_defines:
                self.cql_defines[segment] = []
            self.cql_defines[segment].append(f"define {calc_name}: {cql_expr}")
            item = self._find_item_by_link_id(q.get("item", []), link_id)
            if item is not None and item_allows_initial(item):
                item.setdefault("extension", []).append(build_initial_expression(calc_name))
            return True

        expression = getattr(node, "expression_reference", None) or getattr(node, "reference", None)
        if not expression:
            # Synthetic nodes (e.g. the "path" bridges GoTo/Rhombus branches are
            # rewired through, see inject_bridge_path) never get an
            # expression_reference/reference of their own. Derive their value the
            # same way xls_form/dhis2/openmrs already do via the shared visitor,
            # instead of silently skipping the calculatedExpression/initialExpression.
            if (
                getattr(node, "expression", None) is None
                and issubclass(node.__class__, TriccNodeCalculateBase)
            ):
                node.expression = get_node_expressions(
                    node, kwargs.get("processed_nodes"), process=kwargs.get("process")
                )
            expression = getattr(node, "expression", None)
        if not expression:
            return True

        # calculatedExpression is FHIRPath-only; it can only reach values already
        # answered/computed in *this* Questionnaire (%resource.repeat(item).where(linkId=...)).
        # If at least one reference is captured here, prefer the live-recalculating
        # calculatedExpression; otherwise fall back to a one-time CQL initialExpression.
        references = self._collect_calculate_references(expression)
        captured_in_questionnaire = any(
            not isinstance(ref, TriccReference)
            and self._find_item_by_link_id(q.get("item", []), get_export_name(ref)) is not None
            for ref in references
        )

        if captured_in_questionnaire:
            try:
                fhirpath_expr = self.convert_expression_to_fhirpath(expression)
            except NotImplementedError as e:
                logger.debug(f"Falling back to CQL for {link_id}: {e}")
                fhirpath_expr = None
        else:
            fhirpath_expr = None

        item = self._find_item_by_link_id(q.get("item", []), link_id)

        if fhirpath_expr:
            if item is not None:
                if item.get("type") == "string" and self._expression_returns_boolean(expression):
                    item["type"] = "boolean"
                item.setdefault("extension", []).append(build_calculated_expression_fhirpath(fhirpath_expr))
            return True

        # No in-form reference (or the expression isn't FHIRPath-representable):
        # compute once via CQL and expose it through initialExpression instead.
        try:
            cql_expr = self.convert_expression_to_cql(expression)
        except Exception as e:
            logger.debug(f"Could not convert calculate expression for {link_id}: {e}")
            return True

        if segment not in self.cql_defines:
            self.cql_defines[segment] = []
        self.cql_defines[segment].append(f"define {calc_name}: {cql_expr}")

        if item is not None and item_allows_initial(item):
            item.setdefault("extension", []).append(build_initial_expression(calc_name))

        return True

    def _node_segment(self, node) -> str:
        """Return the Questionnaire / process key for a node."""
        segment = getattr(node, "segment", None) or getattr(node, "process", None) or "main"
        try:
            proc = get_process(node)
            if proc:
                return proc
        except Exception:
            pass
        return segment

    def _segment_for_item(self, node, link_id: str) -> str:
        """Return the Questionnaire that already contains ``link_id``.

        Group nesting can place an item under a parent in ``main`` even when
        ``get_process(node)`` reports another cpg-common-process (e.g.
        ``registration``). Extraction must follow the Questionnaire, not the
        graph process, or prune-empty will drop the rules.
        """
        if link_id:
            for process, q in (self.questionnaires or {}).items():
                if self._find_item_by_link_id(q.get("item", []), link_id) is not None:
                    return process
        return self._node_segment(node)

    def generate_export(self, node, **kwargs):
        """Collect conceptType-driven extraction rules and attach dedup expressions."""
        from tricc_oo.converters.fhir.concept_mapper import resolve_concept_type

        concept_type = resolve_concept_type(
            node, getattr(self.project, "code_systems", None)
        )
        fhir_resource, _, _ = get_fhir_resource(concept_type, getattr(node, "tricc_type", None))
        try:
            link_id = get_export_name(node)
        except Exception:
            link_id = getattr(node, "name", None) or ""

        rule = build_extraction_rule(
            node,
            codesystems=getattr(self.project, "code_systems", None),
            default_code_system=f"{self.base_url}/CodeSystem/tricc",
        )
        if rule is not None:
            q_item = self._find_item_anywhere(rule.link_id)
            apply_questionnaire_item_to_rule(rule, q_item)
            segment = self._segment_for_item(node, rule.link_id)
            self.extraction_rules.setdefault(segment, []).append(rule)
            # Dedup only on items that are actually extracted as Observation/Condition.
            # Notes/groups default to Observation in get_fhir_resource() and must not
            # receive initialExpression (SDC + openSRP $populate).
            if link_id:
                self._attach_dedup_initial_expression(node, fhir_resource, link_id)
        return True

    def _assemble_extraction_maps(self, version: str = "1.0.0") -> None:
        """Build one QuestionnaireResponse → Bundle StructureMap per process."""
        form_key = self.resolve_form_id()
        processes = set(self.questionnaires or {}) | set(self.extraction_rules or {})
        for process in processes:
            rules = list(self.extraction_rules.get(process) or [])
            sm = build_extraction_structuremap(
                rules=rules,
                form_id=form_key,
                process=process,
                base_url=self.base_url,
                version=version,
            )
            self.extraction_maps[process] = sm
            self.fml_mappings[process] = sm.get("_fml") or ""

    def _attach_dedup_initial_expression(self, node, fhir_resource: str, link_id: str) -> None:
        """Auto-attach a dedup ``initialExpression`` for Observation/Condition-typed items.

        Pulls the same code from the current encounter (if already recorded by an
        earlier process in this visit) so the item pre-fills instead of re-asking the
        same question twice. Skipped when the item already has an author-authored
        populate/calculate `initialExpression`/`calculatedExpression` — that takes
        precedence. MedicationRequest/MedicationDispense are out of scope (no node
        type produces them yet — see
        feature/20260812-medication-request-dispense-node.md). See
        feature/20260812-intervention-order-and-dedup.md.
        """
        if fhir_resource not in ("Observation", "Condition"):
            return
        segment = self._segment_for_item(node, link_id)
        q = self.questionnaires.get(segment)
        if not q:
            return
        item = self._find_item_by_link_id(q.get("item", []), link_id)
        if item is None:
            return
        # SDC: initialExpression is illegal on group/display (openSRP ResourceMapper
        # throws IllegalStateException at $populate).
        if not item_allows_initial(item):
            return
        existing = item.get("extension") or []
        if any(e.get("url") in (SDC_EXT_INITIAL_EXPR, SDC_EXT_CALCULATED_EXPR) for e in existing):
            return  # author-authored populate/calculate already covers this item

        if fhir_resource == "Observation":
            # Repeat-aware: a repeat-slot-N item must dedup against slot N specifically,
            # not just any past Observation with this code (see get_observation_cql_accessor).
            cql_expr = get_observation_cql_accessor_for_node(node)
        else:
            code = (getattr(node, "name", None) or link_id).replace("'", "\\'")
            cql_expr = f"Helper.GetConditionValue('{code}')"

        calc_name = f"Dedup_{link_id}"
        if segment not in self.cql_defines:
            self.cql_defines[segment] = []
        self.cql_defines[segment].append(f"define {calc_name}: {cql_expr}")
        item.setdefault("extension", []).append(build_initial_expression(calc_name))

    def _sanitize_questionnaires(self) -> None:
        """Strip SDC-illegal ``initial`` / ``initialExpression`` before write.

        Last-line defence: group and display items must never carry them, or
        openSRP FHIR Data Capture refuses to render the Questionnaire.
        """
        for segment, q in (self.questionnaires or {}).items():
            removed = strip_illegal_initials(q.get("item"))
            if removed:
                logger.warning(
                    "FHIRStrategy: stripped illegal initial/initialExpression from "
                    "%s group/display item(s) in Questionnaire '%s'",
                    removed,
                    segment,
                )

    def export(self, start_pages, version):
        form_id = self.resolve_form_id(start_pages)
        base_path = os.path.join(self.output_path, form_id)
        if not os.path.exists(base_path):
            os.makedirs(base_path)

        # Export Questionnaires — readable filenames; REST id is JSON ``id`` (UUID)
        q_dir = os.path.join(base_path, "questionnaire")
        os.makedirs(q_dir, exist_ok=True)
        for segment, q in self.questionnaires.items():
            file_name = readable_resource_filename(
                q, prefix="Questionnaire", fallback=segment
            )
            path = os.path.join(q_dir, file_name)
            with open(path, "w", encoding="utf-8") as f:
                json.dump(q, f, indent=2, ensure_ascii=False)

        # Export CQL source + Library JSON resources (Phase 2)
        lib_dir = os.path.join(base_path, "library")
        os.makedirs(lib_dir, exist_ok=True)
        for key, cql in self.cql_libraries.items():
            lib = self.libraries.get(key) if self.libraries else None
            stem = to_fhir_id(
                (lib or {}).get("name") or key if isinstance(lib, dict) else key
            )
            # .cql source (useful for debugging)
            cql_path = os.path.join(lib_dir, f"{stem}.cql")
            with open(cql_path, "w", encoding="utf-8") as f:
                f.write(cql)

            # Corresponding FHIR Library JSON (filename from name; id is UUID)
            if isinstance(lib, dict):
                lib_path = os.path.join(
                    lib_dir,
                    readable_resource_filename(lib, prefix="Library", fallback=stem),
                )
                with open(lib_path, "w", encoding="utf-8") as f:
                    json.dump(lib, f, indent=2, ensure_ascii=False)

        # Export extraction StructureMaps (JSON + companion FML)
        if self.extraction_maps:
            sm_dir = os.path.join(base_path, "structure-map")
            os.makedirs(sm_dir, exist_ok=True)
            for process, sm in self.extraction_maps.items():
                payload = {k: v for k, v in sm.items() if not k.startswith("_")}
                file_name = readable_resource_filename(
                    sm, prefix="StructureMap", fallback=f"{process}-extract"
                )
                path = os.path.join(sm_dir, file_name)
                with open(path, "w", encoding="utf-8") as f:
                    json.dump(payload, f, indent=2, ensure_ascii=False)
                fml = sm.get("_fml")
                if fml:
                    map_stem = file_name[: -len(".json")] if file_name.endswith(".json") else file_name
                    with open(os.path.join(sm_dir, f"{map_stem}.map"), "w", encoding="utf-8") as f:
                        f.write(fml)

        logger.info(f"Exported FHIR resources to {base_path}")


    def get_tricc_operation_operand(self, r):
        if isinstance(r, TriccOperation):
            return self.get_tricc_operation_expression(r)
        elif isinstance(r, TriccReference):
            if isinstance(r.value, str):
                return get_observation_cql_accessor(r.value, 1)
            return get_export_name(r.value)
        elif isinstance(r, TriccStatic):
            if isinstance(r.value, str):
                value = f"'{r.value}'"
            else:
                value = str(r.value)
            if value == "True":
                return "true"
            elif value == "False":
                return "false"
            else:
                return value
        elif isinstance(r, bool):
            return 'true' if r else 'false'
        elif isinstance(r, str):
            return f"'{r}'"
        elif isinstance(r, (int, float)):
            return str(r)
        elif isinstance(r, TriccNodeSelectOption):
            return f"'{r.name}'"
        elif isinstance(r, TriccNodeInput):
            return get_observation_cql_accessor_for_node(r)
        elif isinstance(r, TriccNodePopulate):
            return resolve_populate_reference(r, qualified=True)
        elif issubclass(r.__class__, TriccNodeInputModel):
            return get_export_name(r)
        elif issubclass(r.__class__, TriccNodeBaseModel):
            return get_export_name(r)
        else:
            raise NotImplementedError(f"This type of node {r.__class__} is not supported within an operation")

    def convert_expression_to_cql(self, expression):
        if isinstance(expression, TriccOperation):
            return self.get_tricc_operation_expression(expression)
        else:
            return self.get_tricc_operation_operand(expression)

    def _assemble_cql_libraries(self):
        """Turn collected cql_defines into full CQL text + Library resources (Phase 2)."""
        if not self.cql_defines:
            return

        import base64

        form_id = self.resolve_form_id()
        fhir_form = self.fhir_form_id
        # CQL names stay human-readable; FHIR Library.id is a UUID (REST / openSRP style)
        # Dict keys use logical names so export filenames stay readable.
        helper_cql_name = to_fhir_id(fhir_form, "Helper")
        helper_id = fhir_resource_id(form_id, "Library", "Helper")
        helper_key = "Helper"

        # Build helper library (once)
        helper_cql = CQL_HELPER_TEMPLATE.format(
            library_id=helper_cql_name,
            fhir_version=FHIR_VERSION,
            repeat_helpers=cql_helper_repeat_block(FHIR_VERSION),
            populate_helpers=cql_helper_populate_block(),
        )
        self.cql_libraries[helper_key] = helper_cql

        # Create FHIR Library resource for helper
        self.libraries[helper_key] = self._make_library_resource(
            helper_id, helper_cql, form_id, name=helper_cql_name
        )

        # Build one child library per segment/process
        for segment, defines in self.cql_defines.items():
            cql_name = to_fhir_id(fhir_form, segment)
            lib_id = fhir_resource_id(form_id, "Library", segment)
            defines_block = "\n\n".join(defines)

            child_cql = CQL_CHILD_TEMPLATE.format(
                library_id=cql_name,
                fhir_version=FHIR_VERSION,
                helper_library_id=helper_cql_name,
            )
            child_cql += "\n\n" + defines_block + "\n"

            self.cql_libraries[segment] = child_cql

            # Create FHIR Library resource
            self.libraries[segment] = self._make_library_resource(
                lib_id, child_cql, form_id, name=cql_name
            )

    def _make_library_resource(
        self, lib_id: str, cql_text: str, form_id: str, name: Optional[str] = None
    ) -> dict:
        """Create a FHIR Library resource with embedded CQL.

        Args:
            lib_id: Server resource id (UUID preferred).
            cql_text: CQL source text.
            form_id: Human form id for titles.
            name: Optional human-readable ``name`` (CQL library token).
        """
        import base64

        # lib_id is already a UUID from fhir_resource_id; do not re-sanitize hyphens away
        resource_id = lib_id if is_valid_fhir_id(lib_id) else to_fhir_id(lib_id)
        lib_name = name or to_fhir_id(lib_id)
        encoded = base64.b64encode(cql_text.encode("utf-8")).decode("ascii")

        return {
            "resourceType": "Library",
            "id": resource_id,
            "url": f"{self.base_url}/Library/{resource_id}",
            "version": "1.0.0",
            "name": lib_name,
            "title": f"{form_id} - {lib_name} CQL Library",
            "status": "draft",
            "type": {
                "coding": [
                    {
                        "system": "http://terminology.hl7.org/CodeSystem/library-type",
                        "code": "logic-library",
                    }
                ]
            },
            "content": [
                {
                    "contentType": "text/cql",
                    "data": encoded,
                }
            ],
        }

    def convert_expression_to_fhirpath(self, expression):
        # For FHIRPath, similar to CQL but in FHIR context
        # For questionnaire, references to other questions
        if isinstance(expression, TriccOperation):
            return self.get_tricc_operation_expression_fhirpath(expression)
        else:
            return self.get_tricc_operation_operand_fhirpath(expression)

    def _wrap_operand_if_needed(self, r_expr, original_ref) -> str:
        """Wrap a single operand expression with .where($this.exists()).first()
        if the original reference is a Questionnaire answer collection.

        - TriccOperation references are *not* wrapped (the inner operation
          already handles its own scalar output).
        - List sub-references are wrapped element-by-element.
        - TriccReference / TriccNodeInputModel / TriccNodeBaseModel references
          produce answer collections and therefore need the wrapper.
        """
        if isinstance(original_ref, TriccOperation):
            # Inner operation already returns a scalar – do not double-wrap.
            return r_expr

        if isinstance(original_ref, list):
            # Each element in the list is an independent sub-reference.
            for o_r in original_ref:
                r_expr = self._wrap_operand_if_needed(r_expr, o_r)
            # Fallback: treat the whole list expression as a single item.
            return r_expr

        if self._should_wrap_first(original_ref):
            search = self.get_tricc_operation_operand_fhirpath(original_ref)
            replace = f"{search}.where($this.exists()){self._answer_value_suffix(original_ref)}"
            return r_expr.replace(search, replace)

        return r_expr

    def get_tricc_operation_expression_fhirpath(self, operation):
        ref_expressions = []
        original_references = []
        if not hasattr(operation, "reference"):
            return self.get_tricc_operation_operand_fhirpath(operation)
        for r in operation.reference:
            if isinstance(r, list):
                r_expr = [
                    (
                        self.get_tricc_operation_expression_fhirpath(sr)
                        if isinstance(sr, TriccOperation)
                        else self.get_tricc_operation_operand_fhirpath(sr)
                    )
                    for sr in r
                ]
                original_references.append(r)
            elif isinstance(r, TriccOperation):
                r_expr = self.get_tricc_operation_expression_fhirpath(r)
                original_references.append(r)
            else:
                r_expr = self.get_tricc_operation_operand_fhirpath(r)
                original_references.append(r)
            if isinstance(r_expr, TriccReference):
                r_expr = self.get_tricc_operation_operand_fhirpath(r_expr)
            # ───────────────────────────────────────────────────────────────
            ref_expressions.append(r_expr)

        if hasattr(self, f"tricc_operation_fhirpath_{operation.operator}"):
            callable = getattr(self, f"tricc_operation_fhirpath_{operation.operator}")
            return callable(ref_expressions, original_references)
        else:
            # Fallback to CQL operations
            if hasattr(self, f"tricc_operation_{operation.operator}"):
                callable = getattr(self, f"tricc_operation_{operation.operator}")
                return callable(ref_expressions, original_references)
            else:
                raise NotImplementedError(
                    f"This type of operation '{operation.operator}' is not supported"
                )

    def get_tricc_operation_operand_fhirpath(self, r):
        if isinstance(r, TriccOperation):
            return self.get_tricc_operation_expression_fhirpath(r)
        elif isinstance(r, TriccReference):
            # Nested groups are the common case; repeat(item) walks descendants.
            return self._fhirpath_answer(get_export_name(r.value))
        elif isinstance(r, TriccStatic):
            if isinstance(r.value, str):
                value = f"'{r.value}'"
            else:
                value = str(r.value)
            if value == "True":
                return "true"
            elif value == "False":
                return "false"
            else:
                return value
        elif isinstance(r, bool):
            return 'true' if r else 'false'
        elif isinstance(r, str):
            return f"'{r}'"
        elif isinstance(r, (int, float)):
            return str(r)
        elif isinstance(r, TriccNodeSelectOption):
            if self._is_yesno_boolean_select(getattr(r, "select", None)):
                literal = self._yesno_option_boolean_literal(r)
                if literal is not None:
                    return literal
            return f"'{r.name}'"
        elif issubclass(r.__class__, TriccNodeInputModel):
            return self._fhirpath_answer(get_export_name(r))
        elif issubclass(r.__class__, TriccNodeBaseModel):
            return self._fhirpath_answer(get_export_name(r))
        else:
            raise NotImplementedError(f"This type of node {r.__class__} is not supported within an operation")

    # FHIRPath operations, same as CQL for now
    def tricc_operation_fhirpath_and(self, ref_expressions, original_references=None):
        return " and ".join(ref_expressions)

    def tricc_operation_fhirpath_or(self, ref_expressions, original_references=None):
        return " or ".join(ref_expressions)

    def tricc_operation_fhirpath_not(self, ref_expressions, original_references=None):
        # FHIRPath has no unary `not` operator. `not` is a 0-arg function; HAPI
        # rejects `not (expr)` with "The function \"not\" requires 0 parameters".
        return f"({ref_expressions[0]}).not()"

