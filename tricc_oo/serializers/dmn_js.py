"""The CHT extension library that evaluates a project's decision tables: ``dmn-<project>.js``.

feature/20261123-decision-tables.md, "CHT extension library". ``XLSFormCHTStrategy`` writes a
call as ``cht:extension-lib('dmn-<project>.js', 'table', 'policy', 'output', input1, …)``: each
field is read once, instead of once per row in the inline ``if()`` chain. The library holds
every table of the project (so the file is the same for every intervention of a build) with
its cells already parsed, and the same semantics as ``tricc_oo.models.decision_table``:
an empty input is "not entered", an ``integer`` input is rounded down, ``first`` / ``unique``
give the first matching row's output (empty when none), ``rule_order`` the outputs of every
matching row, space-separated (read by ``selected()`` / ``count-selected()``).
"""

from __future__ import annotations

import json
import re
from typing import Any, Dict, List, Optional

from tricc_oo.models.decision_table import CellTest, DecisionTable, compile_table

LIBRARY_PREFIX = "dmn"


def library_name(project_title: Optional[str]) -> str:
    """``dmn-<project>.js``: CHT extension libraries are app-wide, so the name carries the project."""
    slug = re.sub(r"[^a-z0-9]+", "-", (project_title or "").lower()).strip("-")
    return f"{LIBRARY_PREFIX}-{slug}.js" if slug else f"{LIBRARY_PREFIX}.js"


def _test(test: Optional[CellTest]) -> Any:
    if test is None or test.kind == "any":
        return ["-"]
    if test.kind == "null":
        return ["null", test.negated]
    if test.kind == "list":
        return ["or", [_test(t) for t in test.items]]
    if test.kind == "range":
        return ["rng", test.low, test.high, test.low_in, test.high_in]
    return ["cmp", test.op, test.value]


def compile_tables(tables: Dict[str, DecisionTable]) -> Dict[str, Any]:
    """The tables as the library reads them: column names and types, parsed rows."""
    out: Dict[str, Any] = {}
    for table_id in sorted(tables):
        compiled = compile_table(tables[table_id])
        rows: List[Any] = [
            [[_test(t) for t in row.tests], list(row.outputs)] for row in compiled.rows if row.valid
        ]
        out[table_id] = {
            "inputs": [c.type for c in compiled.table.inputs],
            "outputs": [[c.name, c.type] for c in compiled.table.outputs],
            "rows": rows,
        }
    return out


TEMPLATE = r"""// Decision tables of %(title)s, generated by tricc_oo: do not edit, rebuild the forms.
// Called by cht:extension-lib('%(name)s', 'table', 'policy', 'output', input1, input2, ...)
// (tricc feature/20261123-decision-tables.md).
"use strict";

var TABLES = %(tables)s;

function raw(arg) {
  if (arg === undefined || arg === null) return null;
  if (typeof arg !== "object") return arg;
  var v = arg.t === "arr" ? (arg.v && arg.v.length ? arg.v[0] : null) : arg.v;
  if (v !== null && typeof v === "object") v = v.textContent;
  return v === undefined ? null : v;
}

function input(arg, type) {
  var v = raw(arg);
  if (v === null || v === "") return null;
  if (type === "integer" || type === "decimal") {
    var n = typeof v === "number" ? v : parseFloat(v);
    if (isNaN(n)) return null;
    return type === "integer" ? Math.floor(n) : n;
  }
  if (type === "boolean") {
    if (v === true || v === "true" || v === "1" || v === 1 || v === "yes") return true;
    if (v === false || v === "false" || v === "0" || v === 0 || v === "no") return false;
    return null;
  }
  return String(v);
}

function pass(t, v) {
  switch (t[0]) {
    case "-":
      return true;
    case "null":
      return t[1] ? v !== null : v === null;
    case "or":
      for (var i = 0; i < t[1].length; i++) if (pass(t[1][i], v)) return true;
      return false;
    case "rng":
      if (typeof v !== "number") return false;
      return (t[3] ? v >= t[1] : v > t[1]) && (t[4] ? v <= t[2] : v < t[2]);
    default:
      if (v === null) return false;
      if (t[1] === "=") return v === t[2];
      if (typeof v !== "number" || typeof t[2] !== "number") return false;
      if (t[1] === "<") return v < t[2];
      if (t[1] === "<=") return v <= t[2];
      if (t[1] === ">") return v > t[2];
      return v >= t[2];
  }
}

function evaluate(tableId, policy, output, args) {
  var table = TABLES[tableId];
  if (!table) return null;
  var out = 0;
  for (var o = 0; o < table.outputs.length; o++) if (table.outputs[o][0] === output) out = o;
  var values = [];
  for (var i = 0; i < table.inputs.length; i++) values.push(input(args[i], table.inputs[i]));
  var found = [];
  for (var r = 0; r < table.rows.length; r++) {
    var tests = table.rows[r][0];
    var ok = true;
    for (var c = 0; c < tests.length && ok; c++) ok = pass(tests[c], values[c]);
    if (!ok) continue;
    found.push(table.rows[r][1][out]);
    if (policy !== "rule_order") break;
  }
  return { list: policy === "rule_order", type: table.outputs[out][1], values: found };
}

module.exports = function (table, policy, output) {
  var args = Array.prototype.slice.call(arguments, 3);
  var result = evaluate(String(raw(table)), String(raw(policy)), String(raw(output)), args);
  if (!result || result.values.length === 0) return { t: "str", v: "" };
  if (result.list) return { t: "str", v: result.values.map(String).join(" ") };
  var value = result.values[0];
  if (typeof value === "number") return { t: "num", v: value };
  if (typeof value === "boolean") return { t: "bool", v: value };
  return { t: "str", v: String(value) };
};
module.exports.evaluate = evaluate;
"""


def build_dmn_js(tables: Dict[str, DecisionTable], project_title: Optional[str] = None) -> str:
    """The library source for these tables."""
    return TEMPLATE % {
        "title": project_title or "the project",
        "name": library_name(project_title),
        "tables": json.dumps(compile_tables(tables), ensure_ascii=False, separators=(",", ":")),
    }
